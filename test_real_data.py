"""Tests against real public data: a head slice of the GIAB HG002 benchmark VCF.

The slice is verbatim public reference data (Genome in a Bottle HG002, GRCh38,
NISTv4.2.1). The perturbed copy used by the comparison tests is mechanically
derived TEST DATA, not a second observation of the subject; it carries a
``##gtt_synthetic`` header and GTT flags every report generated from it.

All tests skip if the fixtures are absent (they are generated by
``scripts/make_real_slice.py`` and ``scripts/make_perturbed_slice.py``).
"""
import json
import os
import unittest

from gtt.compare import CTX_FILTERED, CTX_NO_RECORD, CTX_OTHER_ALLELE, compare_files
from gtt.validate import infer_build
from gtt.vcfio import VcfReader, read_header

FIX = os.path.join(os.path.dirname(__file__), "fixtures")
REAL = os.path.join(FIX, "hg002_chr1_head.vcf")
PERTURBED = os.path.join(FIX, "hg002_chr1_head_perturbed.vcf")
MANIFEST = os.path.join(FIX, "hg002_chr1_head_perturbed.manifest.json")


@unittest.skipUnless(os.path.exists(REAL), "real-data slice not generated")
class TestRealHeader(unittest.TestCase):
    def test_build_and_sample(self):
        h = read_header(REAL)
        self.assertEqual(h.fileformat, "VCFv4.2")
        self.assertEqual(h.samples, ["HG002"])
        self.assertTrue(h.chr_prefixed)
        self.assertEqual(h.contigs["chr1"], 248956422)
        self.assertFalse(h.synthetic)
        build, evidence = infer_build(h)
        self.assertEqual(build, "GRCh38")
        self.assertIn("248956422", evidence)

    def test_giab_filter_and_format_vocabulary_parsed(self):
        h = read_header(REAL)
        for f in ("GQlessthan70", "discordantunfiltered", "alleleimbalance"):
            self.assertIn(f, h.filters)
        for k in ("GT", "DP", "GQ", "AD", "ADALL", "PS"):
            self.assertIn(k, h.formats)

    def test_real_records_parse(self):
        r = VcfReader(REAL)
        calls = list(r)
        self.assertEqual(r.stats.records, 50000)
        self.assertGreaterEqual(r.stats.alleles_emitted, 50000)
        self.assertTrue(all(c.contig == "chr1" for c in calls))
        self.assertTrue(all(c.pos >= 1 for c in calls))
        self.assertTrue(all(set(c.ref) <= set("ACGTN") for c in calls))
        # Positions are non-decreasing in the published file.
        positions = [c.orig_pos for c in calls]
        self.assertEqual(positions, sorted(positions))
        # Genotypes are real calls, so every status seen must be a known one.
        self.assertTrue({c.gt_status for c in calls} <= {
            "het", "hom_alt", "hemizygous", "hom_ref", "no_call", "other_alt_only"})
        self.assertEqual(calls[0].sample, "HG002")

    def test_first_published_record_matches_the_file(self):
        c = next(iter(VcfReader(REAL)))
        self.assertEqual((c.contig, c.orig_pos, c.orig_ref, c.orig_alt),
                         ("chr1", 602113, "T", "TGCCCA"))
        self.assertEqual(c.var_type, "insertion")


@unittest.skipUnless(os.path.exists(REAL), "real-data slice not generated")
class TestRealSelfComparison(unittest.TestCase):
    """Comparing a file against itself must report no differences at all."""

    def test_identity(self):
        res = compare_files(REAL, REAL)
        self.assertEqual(res.n_baseline_only, 0)
        self.assertEqual(res.n_followup_only, 0)
        self.assertEqual(res.n_genotype_differences, 0)
        self.assertEqual(res.n_shared, res.baseline_stats.alleles_emitted)
        self.assertEqual(res.summary()["jaccard"], 1.0)
        self.assertEqual(res.contigs_compared, ["chr1"])

    def test_identity_under_pass_only(self):
        res = compare_files(REAL, REAL, pass_only=True)
        self.assertEqual((res.n_baseline_only, res.n_followup_only), (0, 0))
        self.assertGreater(res.n_shared, 0)


@unittest.skipUnless(os.path.exists(PERTURBED) and os.path.exists(MANIFEST),
                     "perturbed fixture not generated")
class TestRealPerturbedComparison(unittest.TestCase):
    """GTT's output must match the perturbation recipe, not merely itself."""

    @classmethod
    def setUpClass(cls):
        with open(MANIFEST, encoding="utf-8") as fh:
            cls.manifest = json.load(fh)
        cls.res = compare_files(REAL, PERTURBED, collect=True)
        cls.res_pass = compare_files(REAL, PERTURBED, collect=True, pass_only=True)

    def test_dropped_records_are_reported_as_baseline_only(self):
        expected = set(self.manifest["expected_baseline_only_keys"])
        observed = {r["variant"] for r in self.res.baseline_only_rows}
        self.assertEqual(observed, expected)
        self.assertEqual(self.res.n_followup_only, 0)

    def test_dropped_record_contexts_are_explained(self):
        contexts = set(self.res.baseline_only_contexts)
        self.assertTrue(contexts <= {CTX_NO_RECORD, CTX_OTHER_ALLELE}, contexts)
        self.assertEqual(sum(self.res.baseline_only_contexts.values()),
                         self.res.n_baseline_only)

    def test_genotype_edits_appear_as_shared_with_differing_genotype(self):
        expected = set(self.manifest["expected_genotype_changed_keys"])
        observed = {r["variant"] for r in self.res.genotype_difference_rows}
        self.assertEqual(observed, expected)
        # A genotype change never moves a variant out of the shared set.
        self.assertTrue(expected <= {r["variant"] for r in self.res.shared_rows})

    def test_filter_edits_only_matter_under_pass_only(self):
        filtered = set(self.manifest["expected_filtered_keys"])
        shared_default = {r["variant"] for r in self.res.shared_rows}
        self.assertTrue(filtered <= shared_default)
        moved = {r["variant"] for r in self.res_pass.baseline_only_rows
                 if r["other_file_context"] == CTX_FILTERED}
        self.assertEqual(moved, filtered)
        self.assertEqual(self.res_pass.n_baseline_only,
                         self.res.n_baseline_only + len(filtered))

    def test_perturbed_input_is_flagged_as_synthetic(self):
        self.assertTrue(self.res.followup_header.synthetic)
        self.assertTrue(any("SYNTHETIC TEST FIXTURE" in w
                            for w in self.res.compatibility.warnings))

    def test_sample_identity_recognized(self):
        self.assertIn("HG002", self.res.compatibility.sample_note)


if __name__ == "__main__":
    unittest.main()
